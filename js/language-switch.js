    function getCurrentLanguage() {
        return localStorage.getItem("site_lang") || "fr";
    }

    function setLang(lang) {
        if (!translations[lang]) lang = "en";
        localStorage.setItem("site_lang", lang);
        document.documentElement.lang = lang;

        document.querySelectorAll("[data-i18n]").forEach(function (el) {
            const key = el.getAttribute("data-i18n");
            const val = translations[lang] && translations[lang][key];
            if (val === undefined) return;

            if (el.tagName === "TITLE") {
                document.title = val;
            } else if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                el.value = val;
            } else if (el.querySelectorAll("[data-i18n]").length === 0) {
                el.innerHTML = val;
            } else {
                const textNodes = Array.from(el.childNodes).filter(node => node.nodeType === Node.TEXT_NODE);
                if (textNodes.length > 0) {
                    textNodes[0].textContent = val;
                } else {
                    el.innerHTML = val;
                }
            }
        });

        document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
            const key = el.getAttribute("data-i18n-placeholder");
            const val = translations[lang] && translations[lang][key];
            if (val !== undefined) {
                el.setAttribute("placeholder", val);
            }
        });

        document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
            const key = el.getAttribute("data-i18n-title");
            const val = translations[lang] && translations[lang][key];
            if (val !== undefined) {
                el.setAttribute("title", val);
            }
        });

        document.querySelectorAll("#btn-lang-en, .btn-lang-en").forEach(b => b.classList.toggle("active", lang === "en"));
        document.querySelectorAll("#btn-lang-fr, .btn-lang-fr").forEach(b => b.classList.toggle("active", lang === "fr"));

        if (typeof window.onSiteLanguageChanged === "function") {
            window.onSiteLanguageChanged(lang);
        }

        try {
            window.dispatchEvent(new CustomEvent("languagechange", { detail: { lang } }));
        } catch (e) {}
    }

    window.setLang = setLang;
    window.getCurrentLanguage = getCurrentLanguage;
    window.siteTranslations = translations;
    window.t = function(key, fallback = "") {
        const lang = getCurrentLanguage();
        return (translations[lang] && translations[lang][key]) || fallback || key;
    };

    document.addEventListener("DOMContentLoaded", function () {
        setLang(getCurrentLanguage());
    });

    window.addEventListener("storage", function (event) {
        if (event.key === "site_lang" && event.newValue) {
            setLang(event.newValue);
        }
    });
